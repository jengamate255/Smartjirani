package com.smartjirani.core.designsystem.theme

import androidx.compose.ui.unit.dp

/**
 * 8-point rhythm from the Ujamaa spacing scale.
 *
 * xs icon-to-label gaps · sm tag/input padding · md card padding ·
 * lg section headers · xl major landmarks.
 */
object SmartSpacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 16.dp
    val lg = 24.dp
    val xl = 32.dp
}
